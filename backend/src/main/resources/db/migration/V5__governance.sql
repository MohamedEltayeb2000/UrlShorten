-- Approvals and recorded policy decisions. run_id/node_id are plain columns (no foreign keys) like the other
-- audit-style tables so history survives any future run clean-up.
create table approval (
    id               bigint generated by default as identity primary key,
    run_id           bigint        not null,
    node_id          varchar(64)   not null,
    kind             varchar(24)   not null,
    status           varchar(16)   not null,
    actor_id         varchar(64),
    comment          varchar(2000),
    policy_reason    varchar(500),
    artifact_version int,
    created_at       timestamp with time zone not null,
    decided_at       timestamp with time zone
);
create index idx_approval_run on approval (run_id, id);
create index idx_approval_status on approval (status);

create table policy_decision (
    id             bigint generated by default as identity primary key,
    run_id         bigint        not null,
    node_id        varchar(64),
    rule           varchar(64)   not null,
    outcome        varchar(20)   not null,
    reason         varchar(500)  not null,
    policy_version varchar(16)   not null,
    created_at     timestamp with time zone not null
);
create index idx_policy_decision_run on policy_decision (run_id, id);
