-- Run/node ids below are plain bigint columns on purpose: no foreign keys to the
-- orchestration tables (owned by another migration), so this migration stands alone.
create table artifact (
    id                  bigint generated by default as identity primary key,
    run_id              bigint        not null,
    node_id             varchar(64)   not null,
    artifact_type       varchar(48)   not null,
    version             int           not null,
    content             varchar(100000) not null,
    checksum            varchar(64)   not null,
    status              varchar(16)   not null,
    parent_artifact_ids varchar(500)  not null default '',
    input_refs          varchar(1000) not null default '',
    created_by          varchar(64)   not null,
    created_at          timestamp with time zone not null,
    constraint uq_artifact_version unique (run_id, node_id, artifact_type, version)
);
create index idx_artifact_run on artifact (run_id);

create table audit_event (
    id             bigint generated by default as identity primary key,
    run_id         bigint,
    actor_type     varchar(16)   not null,
    actor_id       varchar(64)   not null,
    event_type     varchar(48)   not null,
    occurred_at    timestamp with time zone not null,
    details        varchar(4000),
    correlation_id varchar(64)
);
create index idx_audit_run on audit_event (run_id, id);

create table stage_attempt (
    id            bigint generated by default as identity primary key,
    run_node_id   bigint       not null,
    attempt       int          not null,
    status        varchar(24)  not null,
    started_at    timestamp with time zone not null,
    ended_at      timestamp with time zone,
    provider_used varchar(32),
    fallback_used boolean      not null default false,
    error         varchar(1000)
);
create index idx_stage_attempt_node on stage_attempt (run_node_id, attempt);
