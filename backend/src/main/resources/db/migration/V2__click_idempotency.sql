create table click_event (
    id            bigint generated by default as identity primary key,
    short_link_id bigint not null,
    occurred_at   timestamp with time zone not null,
    referrer      varchar(255),
    user_agent    varchar(255),
    request_id    varchar(64),
    constraint fk_click_link foreign key (short_link_id) references short_link (id)
);
create index idx_click_link_time on click_event (short_link_id, occurred_at);
create index idx_click_time on click_event (occurred_at);

create table idempotency_record (
    id            bigint generated by default as identity primary key,
    idem_key      varchar(128) not null,
    fingerprint   varchar(64)  not null,
    short_link_id bigint       not null,
    created_at    timestamp with time zone not null,
    expires_at    timestamp with time zone not null,
    constraint uq_idem_key unique (idem_key),
    constraint fk_idem_link foreign key (short_link_id) references short_link (id)
);
