create table agent_run (
    id                      bigint generated by default as identity primary key,
    workflow_name           varchar(64),
    scenario_type           varchar(32),
    raw_requirement         varchar(4000) not null,
    normalized_requirement  varchar(4000),
    status                  varchar(32) not null,
    plan_version            int not null default 1,
    created_at              timestamp with time zone not null,
    started_at              timestamp with time zone,
    completed_at            timestamp with time zone
);
create index idx_agent_run_created on agent_run (created_at);

create table run_node (
    id                bigint generated by default as identity primary key,
    run_id            bigint not null,
    node_id           varchar(64) not null,
    name              varchar(128) not null,
    status            varchar(32) not null,
    attempt_count     int not null default 0,
    depends_on        varchar(1000) not null default '',
    requires_approval boolean not null default false,
    started_at        timestamp with time zone,
    completed_at      timestamp with time zone,
    error_code        varchar(64),
    error_summary     varchar(1000),
    constraint uq_run_node unique (run_id, node_id),
    constraint fk_run_node_run foreign key (run_id) references agent_run (id)
);

create table node_transition (
    id          bigint generated by default as identity primary key,
    run_node_id bigint not null,
    from_status varchar(32),
    to_status   varchar(32) not null,
    occurred_at timestamp with time zone not null,
    reason      varchar(500),
    constraint fk_transition_node foreign key (run_node_id) references run_node (id)
);
create index idx_transition_node on node_transition (run_node_id);
