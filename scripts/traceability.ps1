# Regenerates docs/traceability.md from @Requirement / @req tags and the latest test reports.
# Usage: scripts/traceability.ps1 -Phase N   (returns a result object; also writes docs/traceability.md)
param([int]$Phase = 7)
. "$PSScriptRoot/lib.ps1"
$root = Get-Root

# ---- backend: tag -> test classes; classes -> pass/fail from surefire XML
$backendTags = @{}   # req -> list of class simple names
Get-ChildItem (Join-Path $root 'backend/src/test/java') -Recurse -Filter *.java -ErrorAction SilentlyContinue | ForEach-Object {
    $text = Get-Content $_.FullName -Raw
    $cls = [IO.Path]::GetFileNameWithoutExtension($_.Name)
    foreach ($m in [regex]::Matches($text, '@Requirement\("(\d{3}-FR-\d{3})"\)')) {
        $id = $m.Groups[1].Value
        if (-not $backendTags.ContainsKey($id)) { $backendTags[$id] = New-Object System.Collections.ArrayList }
        if (-not $backendTags[$id].Contains($cls)) { [void]$backendTags[$id].Add($cls) }
    }
}
$classResult = @{}
Get-ChildItem (Join-Path $root 'backend/target/surefire-reports') -Filter 'TEST-*.xml' -ErrorAction SilentlyContinue | ForEach-Object {
    [xml]$x = Get-Content $_.FullName
    $ts = $x.testsuite
    $simple = ($ts.name -split '\.')[-1]
    $bad = [int]$ts.failures + [int]$ts.errors
    $classResult[$simple] = if ($bad -eq 0 -and [int]$ts.tests -gt 0) { 'PASS' } else { 'FAIL' }
}

# ---- frontend: tag -> test files; file -> pass/fail from vitest json
$frontTags = @{}
Get-ChildItem (Join-Path $root 'frontend/tests') -Recurse -Include *.test.ts, *.test.tsx -ErrorAction SilentlyContinue | ForEach-Object {
    $text = Get-Content $_.FullName -Raw
    foreach ($m in [regex]::Matches($text, '@req\s+(\d{3}-FR-\d{3})')) {
        $id = $m.Groups[1].Value
        if (-not $frontTags.ContainsKey($id)) { $frontTags[$id] = New-Object System.Collections.ArrayList }
        if (-not $frontTags[$id].Contains($_.Name)) { [void]$frontTags[$id].Add($_.Name) }
    }
}
$fileResult = @{}
$vj = Join-Path $root 'frontend/test-results.json'
if (Test-Path $vj) {
    $j = Get-Content $vj -Raw | ConvertFrom-Json
    foreach ($tr in $j.testResults) { $fileResult[[IO.Path]::GetFileName($tr.name)] = if ($tr.status -eq 'passed') { 'PASS' } else { 'FAIL' } }
}

$owned = Get-OwnedRequirements -UpToPhase 7
$rows = @()
$allIds = @($owned.Keys) | Sort-Object
foreach ($id in $allIds) {
    $tests = @(); $results = @()
    if ($backendTags.ContainsKey($id)) { foreach ($c in $backendTags[$id]) { $tests += "backend:$c"; $results += $(if ($classResult.ContainsKey($c)) { $classResult[$c] } else { 'NOT_RUN' }) } }
    if ($frontTags.ContainsKey($id)) { foreach ($f in $frontTags[$id]) { $tests += "frontend:$f"; $results += $(if ($fileResult.ContainsKey($f)) { $fileResult[$f] } else { 'NOT_RUN' }) } }
    $status = if ($tests.Count -eq 0) { 'MISSING' } elseif ($results -contains 'FAIL' -or $results -contains 'NOT_RUN') { 'FAIL' } else { 'PASS' }
    $rows += [pscustomobject]@{ Requirement = $id; Owner = $owned[$id]; Tests = ($tests -join ', '); Result = $status }
}

$md = @("# Requirement Traceability", "", "Generated by scripts/traceability.ps1 on $((Get-Date).ToUniversalTime().ToString('s'))Z (phase gate: P$Phase).", "",
    "| Requirement | Owner phase | Tests | Result |", "|---|---|---|---|")
foreach ($r in $rows) { $md += "| $($r.Requirement) | $($r.Owner) | $($r.Tests) | $($r.Result) |" }
$pass = @($rows | Where-Object Result -eq 'PASS').Count
$md += ""; $md += "Passing: $pass / $($rows.Count)"
Set-Content -Path (Join-Path $root 'docs/traceability.md') -Value $md -Encoding utf8

$ownedNow = Get-OwnedRequirements -UpToPhase $Phase
$blocking = @($rows | Where-Object { $ownedNow.ContainsKey($_.Requirement) -and $_.Result -ne 'PASS' })
return [pscustomobject]@{ Rows = $rows; Blocking = $blocking; Passing = $pass; Total = $rows.Count }
